'use client';

import { useEffect, useRef, useState } from 'react';
import css from './xr-generated-music-library.module.css';
import { XR_GENERATED_MUSIC_SAMPLES, type GeneratedMusicSample } from './xr-generated-music-samples';

function assetUrl(id: string, asset: 'audio' | 'source') {
  return '/api/xr/music-library?sample=' + encodeURIComponent(id) + '&asset=' + asset;
}

export function XRGeneratedMusicLibrary({ onLoadSample }: { onLoadSample: (sampleId: string) => Promise<void> }) {
  const [activeSource, setActiveSource] = useState<GeneratedMusicSample | null>(null);
  const [sourceText, setSourceText] = useState('');
  const [sourceState, setSourceState] = useState<'loading' | 'ready' | 'error'>('loading');
  const dialog = useRef<HTMLDialogElement>(null);

  useEffect(() => {
    const element = dialog.current;
    if (!element) return;
    if (activeSource && !element.open) element.showModal();
    if (!activeSource && element.open) element.close();
  }, [activeSource]);

  useEffect(() => {
    if (!activeSource) return;
    const controller = new AbortController();
    setSourceText('');
    setSourceState('loading');
    fetch(assetUrl(activeSource.id, 'source'), { cache: 'no-store', credentials: 'same-origin', signal: controller.signal })
      .then(async response => {
        if (!response.ok) throw new Error('Source unavailable');
        const text = await response.text();
        if (text.length > 40_000) throw new Error('Source too large');
        setSourceText(text);
        setSourceState('ready');
      })
      .catch(() => {
        if (!controller.signal.aborted) setSourceState('error');
      });
    return () => controller.abort();
  }, [activeSource]);

  function closeSource() {
    setActiveSource(null);
  }

  return <section className={css.library} aria-labelledby="xr-generated-library-title">
    <div className={css.libraryHeading}>
      <div>
        <p className={css.eyebrow}>LOCAL GENERATIVE SKETCHES</p>
        <h3 id="xr-generated-library-title">Music library</h3>
      </div>
      <p>Original WAVs made with Python. Nothing here uses the linked recording or the IOANA material.</p>
    </div>
    <ul className={css.list}>
      {XR_GENERATED_MUSIC_SAMPLES.map(sample => <li key={sample.id} className={css.item}>
        <div className={css.trackInfo}>
          <h4>{sample.title}</h4>
          <p>{sample.bpm} BPM · {sample.length} · {sample.description}</p>
          <small>{sample.source}</small>
        </div>
        <audio controls preload="none" src={assetUrl(sample.id, 'audio')} aria-label={'Preview ' + sample.title}>
          Your browser does not support audio playback.
        </audio>
        <div className={css.actions}>
          <button type="button" onClick={() => void onLoadSample(sample.id)}>Load into hand-shaping</button>
          <button type="button" className={css.sourceLink} onClick={() => setActiveSource(sample)}>Open Python code</button>
        </div>
      </li>)}
    </ul>

    <dialog
      ref={dialog}
      className={css.dialog}
      aria-labelledby="xr-python-source-title"
      onCancel={closeSource}
      onClose={closeSource}
    >
      {activeSource && <div className={css.dialogContent}>
        <header className={css.dialogHeader}>
          <div>
            <p className={css.eyebrow}>SOURCE CODE · {activeSource.bpm} BPM</p>
            <h3 id="xr-python-source-title">{activeSource.title}</h3>
          </div>
          <button type="button" onClick={closeSource} autoFocus>Close</button>
        </header>
        <p className={css.sourceNote}>The WAV is generated by this Python file. The code and audio are served from this Mac's private sketch folder and stay local.</p>
        <pre className={css.code} aria-live="polite">{sourceState === 'loading' ? 'Opening generator…' : sourceState === 'error' ? 'Could not load the local Python source.' : <code>{sourceText}</code>}</pre>
      </div>}
    </dialog>
  </section>;
}
