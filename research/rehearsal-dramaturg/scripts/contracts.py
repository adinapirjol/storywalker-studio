"""Generate frontend contracts from the authoritative Pydantic JSON Schema."""
import json
from pathlib import Path
from dramaturg.context.models import State
root=Path(__file__).resolve().parents[3]
schema=State.model_json_schema(mode="serialization")
(root/'lib/context-contract.schema.json').write_text(json.dumps(schema,indent=2)+'\n')
def ts(node):
    if '$ref' in node:return node['$ref'].split('/')[-1]
    if 'const' in node:return json.dumps(node['const'])
    if 'enum' in node:return ' | '.join(json.dumps(v) for v in node['enum'])
    if 'anyOf' in node or 'oneOf' in node:return ' | '.join(ts(n) for n in node.get('anyOf',node.get('oneOf')))
    t=node.get('type')
    if t=='array':return '('+ts(node['items'])+')[]'
    if t=='object' and not node.get('properties'):
        additional=node.get('additionalProperties',False)
        return 'Record<string, '+(ts(additional) if isinstance(additional,dict) else 'unknown' if additional else 'never')+'>'
    if t=='object':return '{ '+ '; '.join(json.dumps(k)+('' if k in node.get('required',[]) else '?')+': '+ts(v) for k,v in node.get('properties',{}).items())+' }'
    return {'integer':'number','number':'number','string':'string','boolean':'boolean','null':'null'}.get(t,'unknown')
text='// Generated by scripts/contracts.py. Do not edit.\n'
for name,node in schema.get('$defs',{}).items():text+=f'export type {name} = {ts(node)};\n'
text+='export type ContextState = '+ts(schema)+';\n'
(root/'lib/context-contract.ts').write_text(text)

